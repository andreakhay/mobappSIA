-- Supabase schema for Diocese of Camarines Norte mobile app (temporary project)
-- Keep this schema identical to the production database when you switch later.

-- Table: parishes
CREATE TABLE public.parishes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    municipality TEXT,
    vicariate TEXT,
    address TEXT,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    logo_url TEXT,
    hero_image_url TEXT,
    patron TEXT,
    feast_day TEXT,
    description TEXT,
    clergy JSONB,
    contact_phone TEXT,
    contact_email TEXT
);

-- Table: mass_schedules
CREATE TABLE public.mass_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parish_id BIGINT REFERENCES public.parishes(id) ON DELETE CASCADE,
    day_of_week TEXT,          -- e.g., 'Monday'
    date DATE,                 -- for special/one‑off masses (optional)
    time TIME NOT NULL,
    is_special BOOLEAN DEFAULT FALSE,
    notes TEXT
);

-- Table: leadership (bishop, vicar general, etc.)
CREATE TABLE public.leadership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role TEXT NOT NULL,        -- e.g., 'Bishop', 'Vicar General'
    name TEXT NOT NULL,
    photo_url TEXT,
    bio TEXT
);

-- Table: announcements (news, events)
CREATE TABLE public.announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    image_url TEXT
);

-- Simple Row‑Level Security policies to allow public read‑only access
-- Enable RLS on each table
ALTER TABLE public.parishes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mass_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leadership ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;

-- Allow SELECT for the anon role (public)
CREATE POLICY "public select" ON public.parishes FOR SELECT USING (true);
CREATE POLICY "public select" ON public.mass_schedules FOR SELECT USING (true);
CREATE POLICY "public select" ON public.leadership FOR SELECT USING (true);
CREATE POLICY "public select" ON public.announcements FOR SELECT USING (true);

